import { EntityManager } from 'typeorm';
import { env } from '../config/env';
import { Tenant } from '../entities/tenant.entity';
import { AppError } from '../utils/errors';

/**
 * The organisation a request is scoped to, named by `DEFAULT_TENANT_CODE`.
 *
 * Every account lookup that can only mean "inside this organisation" goes through here, so the
 * single-tenant assumption lives in one file instead of being repeated at each call site — which is
 * also the one place a later release has to change when a request starts carrying its own tenant.
 *
 * The row is read rather than hard-coded because an id generated by a migration is not something the
 * code should remember: the seed, the sign-in gate and the admin list all have to agree on the same
 * organisation, and agreeing on a database row is what keeps them honest.
 */
export async function resolveTenant(em: EntityManager): Promise<Tenant> {
  const tenant = await em.findOne(Tenant, { where: { code: env.tenant.defaultCode } });
  if (!tenant) {
    throw new AppError(503, 'This deployment has no organisation configured', {
      code: 'TENANT_NOT_CONFIGURED',
      tenantCode: env.tenant.defaultCode,
    });
  }
  return tenant;
}
